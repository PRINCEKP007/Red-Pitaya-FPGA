#!/usr/bin/env python3
"""Bit-exact reference model of osc_cs, the compressive-measurement block.

For every block of N consecutive 125 MSPS samples the FPGA sends ONE number,
a weighted sum (linear combination) of those samples:

    y[m] = sum_{i=0}^{N-1} w[m*N + i] * x[m*N + i]

The weights come from a table of L entries (L a multiple of N, L <= 1024)
that repeats forever, so the measurement matrix Phi is block-diagonal with
P = L/N distinct rows:

    window of L samples  x (L)  ->  P measurements  y = Phi x,   Phi is P x L
    row r of Phi has w[r*N .. r*N+N-1] in columns r*N .. r*N+N-1, zeros elsewhere

Output words: bits [15:1] = y rounded to 15 bits, bit 0 = 1 on row 0 of Phi
(start of a table period), so the host can always line measurements up with Phi.

Usage:
    python3 cs_model.py report                # rates + sparse-recovery demo
    python3 cs_model.py gen-rtl <dir>         # regenerate the default weight table RAM
    python3 cs_model.py vectors <dir> <case>  # simulation files (case 0 or 1)
    python3 cs_model.py compare <dir>         # compare RTL output with expected
"""
import sys
import os
import numpy as np

FS        = 125e6
TBL_DEPTH = 1024      # weight table entries
W_BITS    = 16        # weight width, Q1.15 (32767 ~ +1.0)
OUT_BITS  = 15        # measurement width (bit 0 of the word is the frame flag)

DEF_N     = 10        # default block length -> 10:1
DEF_L     = 1000      # default table length -> 100 rows
DEF_SHIFT = 20        # default output shift: |y| up to 16 without saturation


def default_table():
    """+/-1 (x32767) pseudo-random weights from a 16-bit Fibonacci LFSR, seed 0xACE1."""
    lfsr = 0xACE1
    tbl = []
    for _ in range(TBL_DEPTH):
        bit = ((lfsr >> 0) ^ (lfsr >> 2) ^ (lfsr >> 3) ^ (lfsr >> 5)) & 1
        lfsr = (lfsr >> 1) | (bit << 15)
        tbl.append(32767 if (lfsr & 1) else -32767)
    return np.array(tbl, dtype=np.int64)


def measure(x, tbl, n, l, shift):
    """Fixed-point model of osc_cs. x: int16 samples from the moment the block is enabled."""
    x = np.asarray(x, dtype=np.int64)
    words = []
    rnd = (1 << shift) >> 1
    lim = 2**(OUT_BITS - 1)
    nblk = len(x) // n
    for m in range(nblk):
        pos0 = (m * n) % l
        idx = (pos0 + np.arange(n)) % l
        acc = int(np.dot(x[m * n:(m + 1) * n], tbl[idx]))
        y = (acc + rnd) >> shift
        y = min(max(y, -lim), lim - 1)
        words.append((y << 1) | (1 if pos0 == 0 else 0))
    return np.array(words, dtype=np.int64).astype(np.int16)


def phi(tbl, n, l):
    """Measurement matrix (P x L, real units) for one table period."""
    p = l // n
    w = np.asarray(tbl[:l], dtype=float) / 2**(W_BITS - 1)
    m = np.zeros((p, l))
    for r in range(p):
        m[r, r * n:(r + 1) * n] = w[r * n:(r + 1) * n]
    return m


def decode(words, n, l, shift):
    """Host-side decoder: int16 words -> (Y, start).

    Y has one row per complete table period, P measurements each, in real
    units such that Y[k] = Phi @ x_k, where x_k are the L input samples of
    period k (full scale = 1.0). `start` is the index of the first word used.
    """
    w = np.asarray(words, dtype=np.int16)
    p = l // n
    flags = np.nonzero(w & 1)[0]
    if len(flags) == 0:
        raise ValueError("no frame flag found - is the block enabled and L a multiple of N?")
    start = int(flags[0])
    w = w[start:]
    w = w[: len(w) // p * p]
    y = (w.astype(np.int32) >> 1).astype(float) * 2.0**(shift - 30)
    return y.reshape(-1, p), start


# ---------------------------------------------------------------------------
# RTL generation
# ---------------------------------------------------------------------------

def gen_rtl(outdir):
    tbl = default_table()
    lines = ["`timescale 1ns / 1ps",
             "// Generated by prj/stream_app/cs/cs_model.py - do not edit.",
             "// Compressive-measurement weight table, %d x %d bit (Q1.15)." % (TBL_DEPTH, W_BITS),
             "// Power-up contents: +/-1 pseudo-random (16-bit LFSR, seed 0xACE1);",
             "// software can overwrite any entry through the write port.",
             "module osc_cs_tbl (",
             "  input  wire                 clk,",
             "  input  wire                 we,",
             "  input  wire [10-1:0]        waddr,",
             "  input  wire [16-1:0]        wdata,",
             "  input  wire [10-1:0]        raddr,",
             "  output reg  signed [16-1:0] rdata",
             ");",
             "",
             "reg [16-1:0] mem [0:%d];" % (TBL_DEPTH - 1),
             "",
             "initial begin"]
    for a, v in enumerate(tbl):
        lines.append("  mem[%4d] = 16'h%04x;" % (a, int(v) & 0xFFFF))
    lines += ["end",
              "",
              "always @(posedge clk) begin",
              "  if (we)",
              "    mem[waddr] <= wdata;",
              "  rdata <= mem[raddr];",
              "end",
              "",
              "endmodule",
              ""]
    with open(os.path.join(outdir, "osc_cs_tbl.v"), "w") as f:
        f.write("\n".join(lines))


# ---------------------------------------------------------------------------
# Analysis / demo
# ---------------------------------------------------------------------------

def omp(a, y, k):
    """Orthogonal matching pursuit: k-sparse s with a @ s ~= y."""
    res = y.copy()
    sel = []
    an = a / np.linalg.norm(a, axis=0)
    for _ in range(k):
        sel.append(int(np.argmax(np.abs(an.T @ res))))
        coef, *_ = np.linalg.lstsq(a[:, sel], y, rcond=None)
        res = y - a[:, sel] @ coef
    s = np.zeros(a.shape[1])
    s[sel] = coef
    return s


def report():
    n, l, shift = DEF_N, DEF_L, DEF_SHIFT
    p = l // n
    print("block N=%d -> %d:1, table L=%d -> Phi is %dx%d, shift=%d" % (n, n, l, p, l, shift))
    print("output: %.1f M measurements/s = %.0f MB/s per channel"
          % (FS / n / 1e6, FS / n * 2 / 1e6))

    # sparse-recovery demo: 3 tones on the DFT grid of one table period
    rng = np.random.default_rng(3)
    t = np.arange(20 * l)
    bins = [37, 121, 260]                        # x 125 kHz = 4.625, 15.125, 32.5 MHz
    x = sum(0.25 * np.cos(2 * np.pi * b * t / l + rng.uniform(0, 6.28)) for b in bins)
    x += rng.normal(0, 2 / 2**13, len(t))        # ADC noise
    x16 = np.clip(np.round(x * 2**15), -2**15, 2**15 - 1).astype(np.int64) & ~0x3
    words = measure(x16, default_table(), n, l, shift)
    y, start = decode(words, n, l, shift)

    # dictionary: real cosines and sines of the L-point DFT grid
    tt = np.arange(l)
    kk = np.arange(1, l // 2)
    dic = np.hstack([np.cos(2 * np.pi * np.outer(tt, kk) / l), np.sin(2 * np.pi * np.outer(tt, kk) / l)])
    a = phi(default_table(), n, l) @ dic
    s = omp(a, y[0], 2 * len(bins))
    x_hat = dic @ s
    x_true = x16[start * n: start * n + l] / 2**15
    found = sorted(set(int(kk[i % len(kk)]) for i in np.nonzero(s)[0]))
    err = np.linalg.norm(x_hat - x_true) / np.linalg.norm(x_true)
    print("demo: %d tones, %d measurements for %d samples" % (len(bins), p, l))
    print("      recovered bins %s (true %s), reconstruction error %.2f%%" % (found, bins, 100 * err))


# ---------------------------------------------------------------------------
# Simulation vectors
# ---------------------------------------------------------------------------

CASES = [
    # N, L, shift, table writes
    dict(n=10, l=1000, shift=20, writes=[]),
    dict(n=7, l=994, shift=16, writes=[(0, 16384), (1, -20000), (5, 1), (993, -32768)]),
]


def test_input(num=12000):
    rng = np.random.default_rng(11)
    t = np.arange(num)
    x = 0.5 * np.cos(2 * np.pi * 7.3e6 / FS * t) + 0.3 * np.cos(2 * np.pi * 41e6 / FS * t) + rng.normal(0, 0.05, num)
    x16 = np.clip(np.round(x * 2**15), -2**15, 2**15 - 1).astype(np.int64)
    x16[3000:3100] = 32767                      # full-scale burst to exercise saturation
    return x16


def vectors(outdir, case):
    c = CASES[case]
    os.makedirs(outdir, exist_ok=True)
    x = test_input()
    tbl = default_table()
    for a, d in c["writes"]:
        tbl[a] = d
    with open(os.path.join(outdir, "cs_in.hex"), "w") as f:
        for v in x:
            f.write("%04x\n" % (int(v) & 0xFFFF))
    with open(os.path.join(outdir, "cs_cfg.hex"), "w") as f:
        f.write("%08x\n%08x\n%08x\n%08x\n" % (c["n"], c["l"], c["shift"], len(c["writes"])))
        for a, d in c["writes"]:
            f.write("%08x\n" % ((a << 16) | (d & 0xFFFF)))
        f.write("00000000\n" * (64 - 4 - len(c["writes"])))
    np.savetxt(os.path.join(outdir, "cs_expected.txt"), measure(x, tbl, c["n"], c["l"], c["shift"]), fmt="%d")
    print("case %d: N=%d L=%d shift=%d, %d table writes" % (case, c["n"], c["l"], c["shift"], len(c["writes"])))


def compare(outdir):
    exp = np.loadtxt(os.path.join(outdir, "cs_expected.txt"), dtype=np.int64)
    got = np.loadtxt(os.path.join(outdir, "cs_rtl_out.txt"), dtype=np.int64)
    if len(got) != len(exp):
        print("FAIL: RTL produced %d words, expected %d" % (len(got), len(exp)))
        return 1
    bad = np.nonzero(exp != got)[0]
    if len(bad):
        print("FAIL: %d/%d words differ, first at %d: rtl=%d model=%d"
              % (len(bad), len(exp), bad[0], got[bad[0]], exp[bad[0]]))
        return 1
    print("PASS: %d RTL output words match the model bit-exactly" % len(exp))
    return 0


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "report"
    if cmd == "report":
        report()
    elif cmd == "gen-rtl":
        gen_rtl(sys.argv[2])
    elif cmd == "vectors":
        vectors(sys.argv[2], int(sys.argv[3]))
    elif cmd == "compare":
        sys.exit(compare(sys.argv[2]))
    else:
        print(__doc__)
        sys.exit(2)
